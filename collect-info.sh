#!/usr/bin/env bash

# Не позволяем использовать необъявленные переменные.
set -u

# Создаём имя файла с результатами.
OUT="sysinfo-$(hostname)-$(date +%F-%H%M).txt"

# Очищаем файл перед записью результатов.
> "$OUT"

# Функция запуска команды и записи её результата в файл.
run() {
    title=$1
    command=$2

    # Записываем название раздела.
    echo "===== $title =====" >> "$OUT"

    # Выполняем команду с ограничением времени.
    # Результаты и ошибки записываем в файл.
    timeout 10 bash -c "$command" >> "$OUT" 2>&1

    # Добавляем пустую строку между разделами.
    echo "" >> "$OUT"
}

# Основная функция сбора информации.
main() {
    echo "Собираю информацию о системе..."

    run "Система" "uname -a"
    run "Время работы и нагрузка" "uptime"
    run "Информация о дистрибутиве" "cat /etc/os-release"
    run "Процессор" "lscpu"

    echo "Собираю информацию о нагрузке..."

    run "Нагрузка за 5 секунд" "vmstat 1 5"
    run "Топ-10 процессов по CPU" "ps -eo pid,user,%cpu,%mem,comm --sort=-%cpu | head -11"
    run "Топ-10 процессов по памяти" "ps -eo pid,user,%mem,%cpu,comm --sort=-%mem | head -11"

    echo "Собираю информацию о дисках..."

    run "Свободное место" "df -h"
    run "Использование inode" "df -i"

    # Выводим путь к созданному файлу.
    echo "$PWD/$OUT"
}

main
